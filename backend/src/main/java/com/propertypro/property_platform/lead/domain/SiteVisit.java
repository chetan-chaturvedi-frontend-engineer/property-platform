package com.propertypro.property_platform.lead.domain;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.validation.constraints.Email;
import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Pattern;
import jakarta.validation.constraints.Size;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.DynamicUpdate;
import org.hibernate.annotations.Generated;
import org.hibernate.annotations.SoftDelete;
import org.hibernate.annotations.SoftDeleteType;
import org.hibernate.annotations.UpdateTimestamp;

import java.time.Instant;
import java.time.LocalDate;
import java.time.LocalTime;

/**
 * A visitor's visit to a property project, from booking to the visit report. Ownership fields
 * (builder, property, visitor, scheduler) are fixed at creation; assignment, status and the report
 * change only through {@link #assign}, the status methods and {@link #submitReport}, so the checks in
 * {@code V202610271000__create_site_visits} always hold.
 * <p>
 * {@code visitDate}/{@code visitTime} are wall-clock values at the property; every {@link Instant} is UTC.
 */
@Entity
@Table(name = "site_visits")
// Deletes set deleted_at; the visit stays as history.
@SoftDelete(strategy = SoftDeleteType.TIMESTAMP, columnName = "deleted_at")
@DynamicUpdate
@Getter
@Setter
@NoArgsConstructor(access = AccessLevel.PROTECTED)
public class SiteVisit {

	public static final int NAME_MAX_LENGTH = 150;
	public static final int EMAIL_MAX_LENGTH = 255;
	public static final int NOTE_MAX_LENGTH = 5000;
	public static final int VISITED_WITH_MAX_LENGTH = 150;
	public static final int CANCELLATION_REASON_MAX_LENGTH = 1000;
	public static final int MAX_PEOPLE = 100;
	public static final int MAX_DURATION_MINUTES = 1440;
	public static final int MIN_RATING = 1;
	public static final int MAX_RATING = 5;
	private static final String E164 = "^\\+[1-9][0-9]{6,14}$";

	@Id
	@GeneratedValue(strategy = GenerationType.IDENTITY)
	@Setter(AccessLevel.NONE)
	private Long id;

	/** Generated by the database ({@code site_visit_code_seq}). */
	@Generated
	@Column(name = "visit_code", insertable = false, updatable = false)
	@Setter(AccessLevel.NONE)
	private String visitCode;

	/** Owner of the property when the visit was booked. */
	@NotNull
	@Column(name = "builder_id", nullable = false, updatable = false)
	@Setter(AccessLevel.NONE)
	private Long builderId;

	@NotNull
	@Column(name = "property_id", nullable = false, updatable = false)
	@Setter(AccessLevel.NONE)
	private Long propertyId;

	/** The visitor's account; null for walk-ins and visitors without an account. */
	@Column(name = "user_id")
	private Long userId;

	@Column(name = "lead_id")
	private Long leadId;

	@Column(name = "assign_id")
	@Setter(AccessLevel.NONE)
	private Long assignId;

	@Column(name = "assigned_at")
	@Setter(AccessLevel.NONE)
	private Instant assignedAt;

	@Column(name = "scheduled_by", updatable = false)
	@Setter(AccessLevel.NONE)
	private Long scheduledBy;

	@NotNull
	@Column(name = "visit_type", nullable = false, length = 20)
	private SiteVisitType visitType = SiteVisitType.SITE_VISIT;

	@NotNull
	@Column(name = "visit_date", nullable = false)
	@Setter(AccessLevel.NONE)
	private LocalDate visitDate;

	@NotNull
	@Column(name = "visit_time", nullable = false)
	@Setter(AccessLevel.NONE)
	private LocalTime visitTime;

	@NotNull
	@Column(nullable = false, length = 20)
	@Setter(AccessLevel.NONE)
	private SiteVisitStatus status = SiteVisitStatus.SCHEDULED;

	@NotBlank
	@Size(max = NAME_MAX_LENGTH)
	@Column(nullable = false, length = NAME_MAX_LENGTH)
	private String name;

	/** E.164, normalized by the caller. */
	@NotNull
	@Pattern(regexp = E164)
	@Column(nullable = false, length = 16)
	private String mobile;

	@Email
	@Size(max = EMAIL_MAX_LENGTH)
	@Column(length = EMAIL_MAX_LENGTH)
	private String email;

	@NotNull
	@Min(1)
	@Max(MAX_PEOPLE)
	@Column(name = "number_of_people", nullable = false)
	private Short numberOfPeople = 1;

	@Size(max = NOTE_MAX_LENGTH)
	@Column
	private String note;

	@Column(name = "actual_visit_date")
	@Setter(AccessLevel.NONE)
	private Instant actualVisitDate;

	// Visit report, set together by submitReport.
	@Column
	@Setter(AccessLevel.NONE)
	private Integer duration;

	@Column(name = "visited_with", length = VISITED_WITH_MAX_LENGTH)
	@Setter(AccessLevel.NONE)
	private String visitedWith;

	@Column(length = 20)
	@Setter(AccessLevel.NONE)
	private SiteVisitInterest interest;

	@Column(name = "visit_note")
	@Setter(AccessLevel.NONE)
	private String visitNote;

	@Column
	@Setter(AccessLevel.NONE)
	private String feedback;

	@Column
	@Setter(AccessLevel.NONE)
	private Short rating;

	@Column(name = "report_submitted_by")
	@Setter(AccessLevel.NONE)
	private Long reportSubmittedBy;

	@Column(name = "next_follow_up")
	private Instant nextFollowUp;

	@Size(max = NOTE_MAX_LENGTH)
	@Column(name = "follow_up_note")
	private String followUpNote;

	@Column(name = "cancelled_at")
	@Setter(AccessLevel.NONE)
	private Instant cancelledAt;

	@Column(name = "cancellation_reason")
	@Setter(AccessLevel.NONE)
	private String cancellationReason;

	@CreationTimestamp
	@Column(name = "created_at", nullable = false, updatable = false)
	@Setter(AccessLevel.NONE)
	private Instant createdAt;

	@UpdateTimestamp
	@Column(name = "updated_at", nullable = false)
	@Setter(AccessLevel.NONE)
	private Instant updatedAt;

	/**
	 * @param builderId   the property's owner, read from the property, never from the request
	 * @param scheduledBy the authenticated user
	 */
	public SiteVisit(Long propertyId, Long builderId, Long scheduledBy, LocalDate visitDate, LocalTime visitTime,
			String name, String mobile) {
		this.propertyId = propertyId;
		this.builderId = builderId;
		this.scheduledBy = scheduledBy;
		this.visitDate = visitDate;
		this.visitTime = visitTime;
		this.name = name;
		this.mobile = mobile;
	}

	/** Sets the schedule of a new visit, or moves an upcoming one, which then becomes rescheduled. */
	public void schedule(LocalDate visitDate, LocalTime visitTime) {
		if (id != null) {
			requireUpcoming();
			if (!visitDate.equals(this.visitDate) || !visitTime.equals(this.visitTime)) {
				this.status = SiteVisitStatus.RESCHEDULED;
			}
		}
		this.visitDate = visitDate;
		this.visitTime = visitTime;
	}

	/** Sets or clears ({@code null}) the assignee; the caller checks eligibility. */
	public void assign(Long assignId, Instant at) {
		this.assignId = assignId;
		this.assignedAt = assignId == null ? null : at;
	}

	public void confirm() {
		changeStatus(SiteVisitStatus.CONFIRMED);
	}

	public void complete(Instant actualVisitDate) {
		changeStatus(SiteVisitStatus.COMPLETED);
		this.actualVisitDate = actualVisitDate;
	}

	public void cancel(Instant at, String reason) {
		changeStatus(SiteVisitStatus.CANCELLED);
		this.cancelledAt = at;
		this.cancellationReason = reason;
	}

	public void markNoShow() {
		changeStatus(SiteVisitStatus.NO_SHOW);
	}

	/** Replaces the whole report of a completed visit; {@code submittedBy} is the authenticated user. */
	public void submitReport(SiteVisitInterest interest, String visitNote, Integer duration, String visitedWith,
			String feedback, Short rating, Long submittedBy) {
		if (status != SiteVisitStatus.COMPLETED) {
			throw new IllegalStateException("Visit is " + status.getValue());
		}
		this.interest = interest;
		this.visitNote = visitNote;
		this.duration = duration;
		this.visitedWith = visitedWith;
		this.feedback = feedback;
		this.rating = rating;
		this.reportSubmittedBy = submittedBy;
	}

	public boolean hasReport() {
		return reportSubmittedBy != null;
	}

	private void changeStatus(SiteVisitStatus next) {
		if (!status.canChangeTo(next)) {
			throw new IllegalStateException("Visit cannot move from " + status.getValue() + " to " + next.getValue());
		}
		this.status = next;
	}

	private void requireUpcoming() {
		if (!status.isUpcoming()) {
			throw new IllegalStateException("Visit is " + status.getValue());
		}
	}

}
