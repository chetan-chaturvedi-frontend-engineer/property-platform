import { zodResolver } from '@hookform/resolvers/zod';
import Alert from '@mui/material/Alert';
import FormControlLabel from '@mui/material/FormControlLabel';
import Switch from '@mui/material/Switch';
import { useId, useState } from 'react';
import { Controller, useForm } from 'react-hook-form';
import { z } from 'zod';

import { Button } from '@/components/common/Button';
import { FormTextField } from '@/components/common/Input';
import { Modal } from '@/components/common/Modal';
import { applyServerErrors } from '@/utils/helpers';

import { useCreateBlogCategory } from '../../hooks/useBlogs';
import type { BlogCategory } from '../../types/blog.types';

const schema = z.object({
  title: z
    .string()
    .trim()
    .min(1, 'Enter the category title')
    .max(255, 'Title must be at most 255 characters'),
  active: z.boolean(),
});
type Values = z.infer<typeof schema>;

interface BlogCategoryDialogProps {
  open: boolean;
  onClose: () => void;
  /** Receives the new category, e.g. to select it. */
  onCreated: (category: BlogCategory) => void;
}

/** Quick add of a blog category from the blog form; the slug is generated by the backend. */
export function BlogCategoryDialog({ open, onClose, onCreated }: BlogCategoryDialogProps) {
  const formId = useId();
  const create = useCreateBlogCategory();
  const [formError, setFormError] = useState<string | null>(null);
  const { control, handleSubmit, setError } = useForm<Values>({
    resolver: zodResolver(schema),
    defaultValues: { title: '', active: true },
  });

  const onSubmit = handleSubmit(async (values) => {
    setFormError(null);
    try {
      const category = await create.mutateAsync({
        title: values.title,
        status: values.active ? 'active' : 'inactive',
      });
      onCreated(category);
      onClose();
    } catch (error) {
      setFormError(applyServerErrors(error, setError, ['title']));
    }
  });

  return (
    <Modal
      open={open}
      onClose={onClose}
      title="New blog category"
      maxWidth="xs"
      actions={
        <>
          <Button variant="text" onClick={onClose} disabled={create.isPending}>
            Cancel
          </Button>
          <Button type="submit" form={formId} loading={create.isPending}>
            Create category
          </Button>
        </>
      }
    >
      <form
        id={formId}
        noValidate
        className="flex flex-col gap-3 pt-1"
        onSubmit={(event) => {
          // The dialog renders inside the blog form's React tree; keep its submit to itself.
          event.stopPropagation();
          void onSubmit(event);
        }}
      >
        {formError && <Alert severity="error">{formError}</Alert>}
        <FormTextField
          name="title"
          control={control}
          label="Category title"
          required
          fullWidth
          helperText="The URL slug is generated from the title."
          slotProps={{ htmlInput: { maxLength: 255 } }}
        />
        <Controller
          name="active"
          control={control}
          render={({ field: { value, onChange, ...field } }) => (
            <FormControlLabel
              control={
                <Switch {...field} checked={value} onChange={(_, checked) => onChange(checked)} />
              }
              label="Active (published blogs in it are visible)"
            />
          )}
        />
      </form>
    </Modal>
  );
}
